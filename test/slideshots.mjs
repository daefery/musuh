// Screenshots for the slide deck, taken from the real release binary at 1920x1080.
import { spawn } from 'node:child_process';
import fs from 'node:fs'; import path from 'node:path'; import os from 'node:os';
import { launch } from './browser.mjs';
const out = path.resolve('docs/slides'); const port = 8250;
const run = fs.mkdtempSync(path.join(os.tmpdir(), 'musuh-slides-'));
const srv = spawn(path.resolve('target/release/musuh'), ['--no-open', '--port', String(port)], { cwd: run, stdio: 'ignore' });
const wait = (ms) => new Promise(r => setTimeout(r, ms));
await wait(800);
const b = await launch();
const p = await b.newPage({ viewport: { width: 1600, height: 900 } });
p.on('dialog', d => d.accept());
const until = async (fn, ms = 60000) => { const t0 = Date.now(); while (Date.now() - t0 < ms) { if (await p.evaluate(fn)) return; await wait(80); } };
await p.goto(`http://127.0.0.1:${port}/`); await p.waitForSelector('.scn');
await p.fill('#f-nama', 'Peserta Satu'); await p.click('[data-speed="10"]'); await p.click('button[type=submit]');
await until(() => app.view && app.view.seenIps.includes('198.51.100.23'));
await p.evaluate(() => command('block', '198.51.100.23'));
await until(() => app.view.seenIps.includes('203.0.113.45'));
await p.click('#gsb [data-speed="1"]');
await p.click('#t-trainer'); await wait(600);
await p.locator('.alert').first().click(); await wait(400);
await p.screenshot({ path: `${out}/shot-adapt.png` });
await p.click('#t-trainer'); await wait(400);
await p.screenshot({ path: `${out}/shot-ops.png` });
await p.click('#gsb [data-speed="10"]');
await p.evaluate(() => command('block', '203.0.113.45')); await wait(300);
await p.evaluate(() => control({ handover: true }));
await until(() => app.view.finished && app.view.rapor);
await p.click('#gsb [data-go="rapor"]'); await p.waitForSelector('.paper');
await p.click('#r-test'); await until(() => document.querySelector('#r-out .vres.ok'));
{ const r = await p.evaluate(() => app.view.rapor); r.total = 98; r.verdict = 'GO'; r.grade = 'SANGAT BAIK';
  const fp = path.join(run, 'rapor-diubah.json'); fs.writeFileSync(fp, JSON.stringify(r, null, 2));
  await p.setInputFiles('#r-file', fp); await until(() => document.querySelector('#r-out .vres.bad')); }
await p.screenshot({ path: `${out}/shot-verify.png` });
await b.close(); srv.kill();
console.log('shots written');
